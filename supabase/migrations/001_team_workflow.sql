-- ---------- 原子切换批次：只清理产品表，处理记录和周统计保留 ----------
create or replace function public.activate_import_batch(p_batch_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_batch public.import_batches%rowtype;
  v_products integer;
begin
  if not public.is_admin() then
    raise exception '只有主管可以导入数据';
  end if;

  select * into v_batch from public.import_batches where id = p_batch_id;
  if v_batch.id is null then
    raise exception '导入批次不存在';
  end if;

  select count(*) into v_products from public.products where batch_id = p_batch_id;
  if v_products = 0 then
    raise exception '批次没有产品数据';
  end if;

  update public.import_batches
  set is_current = false
  where id <> p_batch_id and is_current = true;

  update public.import_batches
  set is_current = true, row_count = v_products, status = '已生效'
  where id = p_batch_id;

  -- 仅保留当前周产品明细，控制免费版 500MB 用量。
  delete from public.products where batch_id <> p_batch_id;

  delete from public.weekly_issue_stats where batch_id = p_batch_id;

  insert into public.weekly_issue_stats
    (batch_id, week_no, week_start, week_end, owner, board_key, assigned_count)
  select
    p_batch_id, v_batch.week_no, v_batch.week_start, v_batch.week_end,
    coalesce(nullif(p.owner, ''), '未分配'), issue_key,
    count(distinct p.msku || '|' || p.shop)::integer
  from public.products p
  cross join lateral unnest(coalesce(p.issue_keys, '{}'::text[])) as issue_key
  where p.batch_id = p_batch_id
  group by coalesce(nullif(p.owner, ''), '未分配'), issue_key;

  insert into public.weekly_issue_stats
    (batch_id, week_no, week_start, week_end, owner, board_key, assigned_count)
  select
    p_batch_id, v_batch.week_no, v_batch.week_start, v_batch.week_end,
    coalesce(nullif(p.owner, ''), '未分配'), '__all__',
    count(distinct p.msku || '|' || p.shop)::integer
  from public.products p
  where p.batch_id = p_batch_id
  group by coalesce(nullif(p.owner, ''), '未分配');

  return jsonb_build_object(
    'batch_id', p_batch_id,
    'row_count', v_products,
    'week_no', v_batch.week_no
  );
end;
$$;

create or replace function public.discard_import_batch(p_batch_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception '只有主管可以清理导入批次';
  end if;
  if exists (select 1 from public.import_batches where id = p_batch_id and is_current = true) then
    raise exception '不能删除当前生效批次';
  end if;
  delete from public.products where batch_id = p_batch_id;
  delete from public.import_batches where id = p_batch_id;
end;
$$;

grant execute on function public.activate_import_batch(bigint) to authenticated;
grant execute on function public.discard_import_batch(bigint) to authenticated;