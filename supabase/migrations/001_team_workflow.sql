create or replace function public.set_action_identity()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  profile_name text;
begin
  if tg_op = 'INSERT' then
    select name into profile_name
    from public.profiles
    where id = auth.uid() and active = true;

    if profile_name is null then
      raise exception '账号未启用或不存在';
    end if;

    new.user_id := auth.uid();
    new.user_name := profile_name;
    new.created_at := coalesce(new.created_at, now());
    new.updated_at := now();
  elsif tg_op = 'UPDATE' then
    new.updated_at := now();
    if public.is_admin() then
      if new.status is distinct from old.status and new.status = '已关闭' then
        new.reviewed_by := auth.uid();
        new.reviewed_at := now();
      end if;
    else
      new.user_id := old.user_id;
      new.user_name := old.user_name;
      new.batch_id := old.batch_id;
      new.created_at := old.created_at;
      new.reviewed_by := old.reviewed_by;
      new.reviewed_at := old.reviewed_at;
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_set_action_identity on public.actions;
create trigger trg_set_action_identity
  before insert or update on public.actions
  for each row execute function public.set_action_identity();

