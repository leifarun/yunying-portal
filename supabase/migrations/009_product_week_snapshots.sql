-- 按导入批次永久保留每个产品的周快照，供产品处理弹窗展示周度指标变化。
create table if not exists public.product_week_snapshots (
  id bigint generated by default as identity primary key,
  batch_id bigint not null references public.import_batches(id) on delete cascade,
  week_no integer not null,
  week_start date not null,
  week_end date not null,
  shop text not null,
  msku text not null,
  asin text,
  fnsku text,
  owner text,
  metrics jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (batch_id, shop, msku)
);

create index if not exists idx_product_week_snapshots_product
  on public.product_week_snapshots (shop, msku, week_start desc);

alter table public.product_week_snapshots enable row level security;

drop policy if exists product_week_snapshots_read on public.product_week_snapshots;
create policy product_week_snapshots_read on public.product_week_snapshots
  for select to authenticated
  using (public.is_active_user());

grant select on public.product_week_snapshots to authenticated;

-- 回填当前批次，确保升级后立刻能查看现有产品快照。
insert into public.product_week_snapshots
  (batch_id, week_no, week_start, week_end, shop, msku, asin, fnsku, owner, metrics)
select
  p.batch_id, b.week_no, b.week_start, b.week_end,
  p.shop, p.msku, p.asin, p.fnsku, p.owner, to_jsonb(p)
from public.products p
join public.import_batches b on b.id = p.batch_id
on conflict (batch_id, shop, msku) do update set
  week_no = excluded.week_no,
  week_start = excluded.week_start,
  week_end = excluded.week_end,
  asin = excluded.asin,
  fnsku = excluded.fnsku,
  owner = excluded.owner,
  metrics = excluded.metrics,
  created_at = now();

-- 原子切换批次时，在删除旧产品明细之前写入当前批次的产品周快照。
create or replace function public.activate_import_batch(p_batch_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_batch public.import_batches%rowtype;
  v_products integer;
begin
  if not public.is_admin() then
    raise exception '只有主管可以导入数据';
  end if;

  select * into v_batch from public.import_batches where id = p_batch_id;
  if v_batch.id is null then
    raise exception '导入批次不存在';
  end if;

  select count(*) into v_products from public.products where batch_id = p_batch_id;
  if v_products = 0 then
    raise exception '批次没有产品数据';
  end if;

  update public.import_batches
  set is_current = false
  where id <> p_batch_id and is_current = true;

  update public.import_batches
  set is_current = true, row_count = v_products, status = '已生效'
  where id = p_batch_id;

  delete from public.product_week_snapshots where batch_id = p_batch_id;

  insert into public.product_week_snapshots
    (batch_id, week_no, week_start, week_end, shop, msku, asin, fnsku, owner, metrics)
  select
    p_batch_id, v_batch.week_no, v_batch.week_start, v_batch.week_end,
    p.shop, p.msku, p.asin, p.fnsku, p.owner, to_jsonb(p)
  from public.products p
  where p.batch_id = p_batch_id;

  -- 仅保留当前周产品明细，控制免费版 500MB 用量；周快照永久保留。
  delete from public.products where batch_id <> p_batch_id;

  delete from public.weekly_issue_stats where batch_id = p_batch_id;

  insert into public.weekly_issue_stats
    (batch_id, week_no, week_start, week_end, owner, board_key, assigned_count)
  select
    p_batch_id, v_batch.week_no, v_batch.week_start, v_batch.week_end,
    coalesce(nullif(p.owner, ''), '未分配'), issue_key,
    count(distinct p.msku || '|' || p.shop)::integer
  from public.products p
  cross join lateral unnest(coalesce(p.issue_keys, '{}'::text[])) as issue_key
  where p.batch_id = p_batch_id
  group by coalesce(nullif(p.owner, ''), '未分配'), issue_key;

  insert into public.weekly_issue_stats
    (batch_id, week_no, week_start, week_end, owner, board_key, assigned_count)
  select
    p_batch_id, v_batch.week_no, v_batch.week_start, v_batch.week_end,
    coalesce(nullif(p.owner, ''), '未分配'), '__all__',
    count(distinct p.msku || '|' || p.shop)::integer
  from public.products p
  where p.batch_id = p_batch_id
  group by coalesce(nullif(p.owner, ''), '未分配');

  return jsonb_build_object(
    'batch_id', p_batch_id,
    'row_count', v_products,
    'week_no', v_batch.week_no
  );
end;
$$;
