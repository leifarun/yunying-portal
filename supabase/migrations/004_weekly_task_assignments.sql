-- 主管每周按组员、按任务板块分配目标数量
create table if not exists public.weekly_task_assignments (
  id bigint generated by default as identity primary key,
  batch_id bigint not null references public.import_batches(id) on delete cascade,
  week_no integer not null,
  week_start date not null,
  week_end date not null,
  owner text not null,
  board_key text not null,
  target_count integer not null default 0 check (target_count >= 0),
  assigned_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (batch_id, owner, board_key)
);

create index if not exists idx_weekly_task_assignments_batch
  on public.weekly_task_assignments (batch_id, owner);

alter table public.weekly_task_assignments enable row level security;

drop policy if exists weekly_assignments_read on public.weekly_task_assignments;
drop policy if exists weekly_assignments_admin on public.weekly_task_assignments;

create policy weekly_assignments_read on public.weekly_task_assignments
  for select to authenticated
  using (
    public.is_active_user()
    and (
      public.is_admin()
      or owner = (select name from public.profiles where id = auth.uid())
    )
  );

create policy weekly_assignments_admin on public.weekly_task_assignments
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

grant select, insert, update, delete on public.weekly_task_assignments to authenticated;
grant usage, select on all sequences in schema public to authenticated;